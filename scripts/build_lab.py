#!/usr/bin/env python3
"""Compose reviewable IOS lab configs. Does not create a Packet Tracer/GNS3 project."""
import argparse
import csv
import hashlib
import io
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASES = {
    "Main-Core": "main/main-core-transit-reference.cfg",
    "Main-GW": "main/main-wan-router.cfg",
    "Main-FW": "main/main-fw-routing-reference.cfg",
    "Main-Edge": "main/main-edge-router.cfg",
    "DBP-GW": "dbp/dbp-wan-router.cfg",
    "BHTQ-GW": "bhtq/bhtq-wan-router.cfg",
    "ISP1": "isp-lab/isp-edge-lab.cfg",
    "ISP2": "isp-lab/isp2-router.cfg",
    "INET-Core": "isp-lab/internet-core-router.cfg",
}
SITES = {"Main": (10, "Main-Core", (10, 20, 30, 40, 50, 60)),
         "DBP": (20, "DBP-GW", (10, 20, 30)),
         "BHTQ": (30, "BHTQ-GW", (10, 20, 30))}
OUTPUT = ROOT / "simulation/generated"


def dhcp_rule(source, server):
    return [" permit udp host 0.0.0.0 eq 68 host 255.255.255.255 eq 67",
            f" permit udp {source} eq 68 host 255.255.255.255 eq 67",
            f" permit udp {source} eq 68 host {server} eq 67"]


def site_overlay(site):
    octet, _, user_vlans = SITES[site]
    dhcp = f"10.{octet}.70." + ("10" if site == "Main" else "6")
    lines = ["! TV3 ingress policy and DHCP relay; generated by scripts/build_lab.py."]
    pools = []
    ping_networks = ("10.10.10.0", "10.10.20.0", "10.20.10.0", "10.30.10.0")
    for vlan in (*user_vlans, 100, 120):
        guest = vlan == 100
        wildcard = "0.0.1.255" if guest else ("0.0.0.255" if vlan == 120 else "0.0.0.127")
        source = f"10.{octet}.{vlan}.0 {wildcard}"
        acl = f"{site.upper()}-V{vlan}-IN"
        lines.append(f"ip access-list extended {acl}")
        lines.extend(dhcp_rule(source, dhcp))
        dns = "192.0.2.100" if guest else dhcp
        for proto in ("udp", "tcp"):
            lines.append(f" permit {proto} {source} host {dns} eq 53")
        if not guest:
            for target in ("10.10.70.11", "10.10.70.14", "10.10.80.10"):
                for port in (80, 443) if target != "10.10.80.10" else (80,):
                    lines.append(f" permit tcp {source} host {target} eq {port}")
            if (site == "Main" and vlan == 30) or (site != "Main" and vlan == 10):
                for port in (80, 11112):
                    lines.append(f" permit tcp {source} host 10.10.70.12 eq {port}")
            if (site == "Main" and vlan == 40) or (site != "Main" and vlan == 20):
                for port in (80, 443):
                    lines.append(f" permit tcp {source} host 10.10.70.13 eq {port}")
            if f"10.{octet}.{vlan}.0" in ping_networks:
                for destination in ping_networks:
                    lines.append(f" permit icmp {source} {destination} 0.0.0.127")
        for private, wild in (("10.0.0.0", "0.255.255.255"), ("172.16.0.0", "0.15.255.255"),
                              ("192.168.0.0", "0.0.255.255"), ("169.254.0.0", "0.0.255.255")):
            lines.append(f" deny ip any {private} {wild} log")
        for port in (80, 443):
            lines.append(f" permit tcp {source} any eq {port}")
        lines.extend([f" permit icmp {source} host 192.0.2.100", " deny ip any any log"])
        lines.extend([f"interface GigabitEthernet0/0.{vlan}",
                      f" ip helper-address {dhcp}", f" ip access-group {acl} in"])
        prefix, mask, start, end, count = ((23, "255.255.254.0", f"10.{octet}.100.11", f"10.{octet}.101.254", 500)
                                          if guest else (24, "255.255.255.0", f"10.{octet}.120.11", f"10.{octet}.120.254", 244)
                                          if vlan == 120 else (25, "255.255.255.128", f"10.{octet}.{vlan}.7", f"10.{octet}.{vlan}.126", 120))
        pools.append(dict(site=site, name=f"{site}-V{vlan}", vlan=vlan, server=dhcp,
                          network=f"10.{octet}.{vlan}.0/{prefix}", mask=mask,
                          gateway=f"10.{octet}.{vlan}.1", dns=dns, start=start, end=end, max_users=count))
    server_net = f"10.{octet}.70.0 " + ("0.0.0.31" if site == "Main" else "0.0.0.15")
    lines += [f"ip access-list extended {site.upper()}-SERVER-IN",
              f" permit udp host {dhcp} eq 67 any eq 67",
              f" permit udp host {dhcp} eq 67 any eq 68",
              f" permit udp host {dhcp} eq 53 10.0.0.0 0.255.255.255",
              f" permit tcp {server_net} any established",
              f" permit icmp {server_net} any echo-reply",
              f" permit udp host {dhcp} host 192.0.2.100 eq 53",
              f" permit tcp host {dhcp} host 192.0.2.100 eq 53",
              f" permit udp {server_net} host 10.10.70.17 eq 123",
              f" permit udp {server_net} host 10.10.70.17 eq 514"]
    if site != "Main":
        lines.append(f" permit tcp host 10.{octet}.70.7 host 10.10.70.16 eq 22")
    lines += [f" deny ip any 10.0.0.0 0.255.255.255 log",
              f" deny ip any 172.16.0.0 0.15.255.255 log",
              f" deny ip any 192.168.0.0 0.0.255.255 log",
              f" permit tcp {server_net} any eq 80", f" permit tcp {server_net} any eq 443",
              " deny ip any any log", "interface GigabitEthernet0/0.70",
              f" ip access-group {site.upper()}-SERVER-IN in",
              f"ip access-list extended {site.upper()}-MGMT-IN",
              " permit ip host 10.10.90.11 any" if site == "Main" else " remark No local admin workstation authorized",
              f" permit tcp 10.{octet}.90.0 0.0.0.255 host 10.10.90.11 established",
              f" permit icmp 10.{octet}.90.0 0.0.0.255 host 10.10.90.11 echo-reply",
              " deny ip any any log", "interface GigabitEthernet0/0.90",
              f" ip access-group {site.upper()}-MGMT-IN in",
              f"ip access-list extended {site.upper()}-CAMERA-IN",
              f" permit tcp 10.{octet}.110.0 0.0.0.255 host 10.10.90.11 established",
              f" permit icmp 10.{octet}.110.0 0.0.0.255 host 10.10.90.11 echo-reply",
              f" permit udp 10.{octet}.110.0 0.0.0.255 host 10.10.70.17 eq 123",
              " deny ip any any log", "interface GigabitEthernet0/0.110",
              f" ip access-group {site.upper()}-CAMERA-IN in",
              "no ip http server", "no ip http secure-server"]
    return "\n".join(lines) + "\n", pools


def artifacts():
    overlays = {}
    pools = []
    for site, (_, node, _) in SITES.items():
        overlays[node], entries = site_overlay(site)
        pools.extend(entries)
    for node, name in (("Main-FW", "main-fw-policy.inc"), ("Main-Edge", "main-edge-dmz.inc")):
        overlays[node] = (ROOT / "configs/security" / name).read_text(encoding="utf-8")
    output = {}
    for node, path in BASES.items():
        base = (ROOT / "configs" / path).read_text(encoding="utf-8")
        lines = [line for line in base.splitlines() if line.strip() != "end"]
        output[f"configs/{node}.cfg"] = ("! COMPOSED REFERENCE - NOT RUN on IOS. Source: configs/" + path + "\n"
                                         + "! Base comments describe the routing source; the TV3 overlay below adds policy where configured.\n"
                                         + "\n".join(lines) + "\n! TV3 overlay follows; later interface blocks augment earlier ones.\n"
                                         + overlays.get(node, "") + "end\n")
    stream = io.StringIO()
    writer = csv.DictWriter(stream, fieldnames=list(pools[0]), lineterminator="\n")
    writer.writeheader()
    writer.writerows(pools)
    output["dhcp-pools.csv"] = stream.getvalue()
    # Minimal switches support TV4 integration; these are not the campus design/BOM.
    with (ROOT / "simulation/lab/endpoints.csv").open(encoding="utf-8", newline="") as stream:
        endpoints = list(csv.DictReader(stream))
    switches = {name: [] for name in ("Main-Access", "DBP-Access", "BHTQ-Access", "DMZ-Access", "Web-Access")}
    ports = []
    for endpoint in endpoints:
        switch = ("Web-Access" if endpoint['site'] == "Internet" else "DMZ-Access"
                  if endpoint['vlan'] == "80" else endpoint['site'] + "-Access")
        number = len(switches[switch]) + 1
        assert number <= 24, f"Add another test switch for {switch}"
        vlan = int(endpoint['vlan']) or 1
        switches[switch].append((number, endpoint['node'], vlan))
        ports.append(dict(switch=switch, interface=f"FastEthernet0/{number}",
                          endpoint=endpoint['node'], vlan=vlan))
    for name, entries in switches.items():
        site = name.removesuffix('-Access')
        vlans = sorted({vlan for _, _, vlan in entries})
        if site in SITES:
            vlans = sorted(set((*SITES[site][2], 70, 90, 100, 110, 120)))
        lines = ["! Minimal TV4 lab switch; review against TV2 campus module before use.",
                 "! Reference: 2960 with FastEthernet0/1-24 and GigabitEthernet0/1-2.", f"hostname {name}"]
        for vlan in vlans:
            if vlan != 1:
                lines += [f"vlan {vlan}", f" name LAB-V{vlan}"]
        lines += ["interface GigabitEthernet0/1", " description Router-uplink"]
        if site in SITES:
            lines += [" switchport mode trunk", " switchport trunk allowed vlan " + ','.join(map(str, vlans))]
        else:
            lines += [" switchport mode access", f" switchport access vlan {vlans[0]}"]
        lines.append(" no shutdown")
        for number, endpoint, vlan in entries:
            lines += [f"interface FastEthernet0/{number}", f" description {endpoint}",
                      " switchport mode access", f" switchport access vlan {vlan}",
                      " spanning-tree portfast", " spanning-tree bpduguard enable", " no shutdown"]
        if len(entries) < 24:
            lines += [f"interface range FastEthernet0/{len(entries)+1} - 24", " shutdown"]
        lines += ["interface GigabitEthernet0/2", " shutdown", "line vty 0 4", " transport input none", "end"]
        output[f"switches/{name}.cfg"] = '\n'.join(lines) + '\n'
    stream = io.StringIO()
    writer = csv.DictWriter(stream, fieldnames=list(ports[0]), lineterminator="\n")
    writer.writeheader()
    writer.writerows(ports)
    output["switch-ports.csv"] = stream.getvalue()
    hashes = {name: hashlib.sha256(content.encode()).hexdigest() for name, content in sorted(output.items())}
    output["manifest.json"] = json.dumps(dict(status="REFERENCE ONLY - NO RUNTIME ACCEPTANCE", sha256=hashes), indent=2) + "\n"
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if committed artifacts are missing or stale")
    args = parser.parse_args()
    stale = []
    for relative, content in artifacts().items():
        path = OUTPUT / relative
        if args.check:
            if not path.exists() or path.read_bytes() != content.encode():
                stale.append(relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content.encode())
    if stale:
        parser.exit(1, "Stale artifacts; run python3 scripts/build_lab.py: " + ", ".join(stale) + "\n")
    print("OK: composed 9 router + 5 lab switch configs, 18 DHCP pools, port map and manifest" + (" (freshness checked)" if args.check else ""))


if __name__ == "__main__":
    main()
